def rows():
    out = []
    for f in FINDINGS:
        s, sev = score(f[3])
        out.append({"id": f[0], "owasp": f[1], "title": f[2], "vec": f[3],
                    "cvss": s, "sev": SEV_UA[sev], "sev_en": sev,
                    "like": f[4], "impact": f[5], "sla": f[6],
                    "before": f[7], "after": f[8], "fix": f[9]})
    return out


